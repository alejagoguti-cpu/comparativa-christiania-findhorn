const fmtTime = (idx: number) => {
  const s0 = idx * 30;
  const s1 = (idx + 1) * 30;
  const m0 = String(Math.floor(s0 / 60)).padStart(2, '0');
  const r0 = String(s0 % 60).padStart(2, '0');
  const m1 = String(Math.floor(s1 / 60)).padStart(2, '0');
  const r1 = String(s1 % 60).padStart(2, '0');
  return `${m0}:${r0} – ${m1}:${r1}`;
};

